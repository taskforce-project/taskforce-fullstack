// Copie le vérificateur des dossiers (src/harness/verifier) et le moteur compilé (src/harness/engine) dans l'app,
// sous frontend/lib/evidence : l'app vérifie un dossier avec le même code que `npm run verify` (R159, #551). L'app se
// construit depuis frontend/ seul et ne peut pas importer le runner : elle reçoit cette copie, que la CI du runner refait
// et compare. On ne la modifie jamais à la main : on modifie la source, puis on relance `npm run share:app`.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const runner = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(runner, "..", "frontend", "lib", "evidence");
const SOURCES = [
  ["src/harness/verifier", "verifier"],
  ["src/harness/engine", "engine"],
];

rmSync(target, { recursive: true, force: true });
let copied = 0;
for (const [from, to] of SOURCES) {
  mkdirSync(join(target, to), { recursive: true });
  for (const name of readdirSync(join(runner, from)).sort()) {
    const source = readFileSync(join(runner, from, name), "utf8").replace(/\r\n/g, "\n");
    const banner = `// Generated by \`npm run share:app\` in taskforce-runner, from taskforce-runner/${from}/${name}: do not edit.\n`;
    writeFileSync(join(target, to, name), banner + source, "utf8");
    copied++;
  }
}
console.log(`${copied} files copied to frontend/lib/evidence`);
